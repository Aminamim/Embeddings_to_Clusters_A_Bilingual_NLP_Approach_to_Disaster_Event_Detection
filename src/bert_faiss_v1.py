def predict_disaster_tag(query: str, top_k: int = Config.TOP_K, threshold: float = Config.SIMILARITY_THRESHOLD) -> dict:
    """
    Predict the disaster category using weighted majority vote
    among retrieved neighbours.
    """
    results = query_disaster(query, top_k=top_k, threshold=threshold)

    if results.empty:
        return {"predicted_tag": "Unknown / No Match", "confidence": 0.0, "details": results}

    # Weighted majority vote by similarity score
    weighted = results.groupby("disaster_tag")["similarity_score"].sum()
    predicted_tag = weighted.idxmax()
    confidence = weighted.max() / weighted.sum()

    return {
        "predicted_tag": predicted_tag,
        "confidence": round(confidence, 4),
        "details": results,
    }


