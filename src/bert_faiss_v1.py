# Implements Section 1 of the proposal:
#   H = BERT(X) = {h1, h2, ..., hn}
# Then takes the MEAN of all token embeddings (excluding padding) as the
# fixed-size sentence representation.

def generate_embeddings(sentences: list, batch_size: int = Config.BATCH_SIZE) -> np.ndarray:
    """
    Steps (matching the proposal):
      1. Prepend [CLS], append [SEP]
      2. WordPiece tokenization
      3. Token + Position embeddings (Segment = 0 for single sentences)
      4. 12 self-attention layers
      5. Mean-pool all token embeddings → fixed-size vector
    """
    all_embeddings = []

    for start in tqdm(range(0, len(sentences), batch_size), desc="Embedding"):
        batch = sentences[start : start + batch_size]

        # Tokenization: adds [CLS], [SEP], applies WordPiece
        encoded = tokenizer(
            batch,
            padding=True,
            truncation=True,
            max_length=Config.MAX_SEQ_LENGTH,
            return_tensors="pt",
        )
        encoded = {k: v.to(Config.DEVICE) for k, v in encoded.items()}

        with torch.no_grad():
            outputs = model(**encoded)
            # outputs.last_hidden_state: (batch, seq_len, 768)
            hidden_states = outputs.last_hidden_state

        # Mean pooling over non-padding tokens
        attention_mask = encoded["attention_mask"].unsqueeze(-1)  # (batch, seq_len, 1)
        masked_hidden = hidden_states * attention_mask
        summed = masked_hidden.sum(dim=1)                        # (batch, 768)
        counts = attention_mask.sum(dim=1).clamp(min=1)          # avoid /0
        mean_pooled = (summed / counts).cpu().numpy()

        all_embeddings.append(mean_pooled)

    return np.vstack(all_embeddings).astype("float32")


