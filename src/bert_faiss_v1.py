# Implements Section 2 of the proposal:
#   Store (E(S), Tag(S)) pairs; retrieve via ANN with threshold θ = 0.8
#
# We use an Inner-Product index on L2-normalised vectors so that the
# similarity score equals cosine similarity (range 0–1).

def build_faiss_index(embeddings: np.ndarray) -> faiss.IndexFlatIP:
    # L2-normalise so dot product == cosine similarity
    faiss.normalize_L2(embeddings)
    index = faiss.IndexFlatIP(Config.EMBEDDING_DIM)
    index.add(embeddings)
    print(f"FAISS index built — {index.ntotal} vectors indexed")
    return index


index = build_faiss_index(embeddings.copy())  # copy because normalize_L2 is in-place

# Parallel arrays: index position i → (text, tag)
index_texts = df["text"].tolist()
index_tags = df["disaster_tag"].tolist()

# Given a new query Q:
#   1. Compute E(Q) via BERT
#   2. ANN search in FAISS
#   3. Filter by Similarity(E(Q), E(S_i)) >= θ

def query_disaster(
    query: str,
    top_k: int = Config.TOP_K,
    threshold: float = Config.SIMILARITY_THRESHOLD,
) -> pd.DataFrame:
    # 1. Embed the query
    q_emb = generate_embeddings([query])
    faiss.normalize_L2(q_emb)

    # 2. ANN search
    scores, indices = index.search(q_emb, top_k)
    scores = scores[0]
    indices = indices[0]

    # 3. Apply similarity threshold
    results = []
    for score, idx in zip(scores, indices):
        if idx == -1:
            continue
        if score >= threshold:
            results.append({
                "matched_text": index_texts[idx],
                "disaster_tag": index_tags[idx],
                "similarity_score": round(float(score), 4),
            })

    return pd.DataFrame(results)

